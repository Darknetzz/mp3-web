#!/usr/bin/env python3
"""Build the Lucide icon sprite used by icon() (functions.php) and lucideIcon() (js.php).

Only the icons listed below are included. To add one, put its Lucide name in
ICONS (or TABLE_ICONS for bootstrap-table toolbar icons) and re-run:

    python3 assets/icons/build.py

Writes:
  assets/icons/lucide.svg   <symbol> sprite, referenced with <use href="…#name">
  assets/icons/table.css    CSS mask rules for bootstrap-table's <i> toolbar icons
"""
import os, re, sys, urllib.parse, urllib.request

VERSION = "1.71.0"
BASE = f"https://cdn.jsdelivr.net/npm/lucide-static@{VERSION}/icons/"
OUT = os.path.dirname(os.path.abspath(__file__))

ICONS = [
    # player
    "play", "pause", "square", "skip-back", "skip-forward", "list-start",
    "repeat", "shuffle", "list-end", "cast", "dice-1", "dice-2", "dice-3", "dice-4",
    "dice-5", "dice-6", "volume-x", "volume-1", "volume-2", "heart",
    # navbar, sessions, settings
    "settings", "users", "user", "user-plus", "link", "log-out",
    "circle-check", "info", "search", "sliders-horizontal", "list-video",
    "circle-play", "palette", "panels-top-left", "image", "ellipsis",
    # table rows, playlists, menus
    "list-music", "plus", "circle-plus", "list-ordered", "arrow-up",
    "arrow-down", "circle-minus", "pencil", "download", "upload", "trash-2",
    "list-plus", "copy", "chevron-right", "chevron-left", "chevron-up",
    # queue panel
    "x", "grip-vertical",
    # lyrics panel
    "mic-vocal", "music",
]

# bootstrap-table option name -> Lucide icon (see the icons config in index.php)
TABLE_ICONS = {
    "refresh": "refresh-cw", "toggleOff": "toggle-left", "toggleOn": "toggle-right",
    "columns": "columns-3", "search": "search", "clearSearch": "trash-2",
    "detailOpen": "plus", "detailClose": "minus", "fullscreen": "maximize",
    "paginationSwitchDown": "chevron-down", "paginationSwitchUp": "chevron-up",
}


def fetch(name):
    with urllib.request.urlopen(BASE + name + ".svg", timeout=30) as r:
        svg = r.read().decode("utf-8")
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not m:
        sys.exit(f"unexpected SVG for {name}")
    # Collapse whitespace so the sprite stays compact
    return re.sub(r"\s+", " ", m.group(1)).replace("> <", "><").strip()


def main():
    cache = {}
    def body(n):
        if n not in cache:
            cache[n] = fetch(n)
        return cache[n]

    symbols = "\n".join(
        f'  <symbol id="{n}" viewBox="0 0 24 24">{body(n)}</symbol>' for n in ICONS
    )
    with open(os.path.join(OUT, "lucide.svg"), "w") as f:
        f.write(
            f"<!-- Lucide v{VERSION} (ISC) - https://lucide.dev - generated by build.py -->\n"
            '<svg xmlns="http://www.w3.org/2000/svg">\n' + symbols + "\n</svg>\n"
        )

    rules = []
    for n in sorted(set(TABLE_ICONS.values())):
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
               'stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
               + body(n) + "</svg>")
        uri = "data:image/svg+xml," + urllib.parse.quote(svg, safe=" /:=,.-")
        rules.append(f'.lucide-i.icon-{n} {{ --icon: url("{uri}"); }}')
    with open(os.path.join(OUT, "table.css"), "w") as f:
        f.write(
            f"/* Lucide v{VERSION} (ISC) icons for bootstrap-table's <i> toolbar icons. Generated by build.py. */\n"
            ".lucide-i { display: inline-block; width: 1em; height: 1em; vertical-align: -0.125em;"
            " background-color: currentColor; -webkit-mask: var(--icon) center / contain no-repeat;"
            " mask: var(--icon) center / contain no-repeat; }\n" + "\n".join(rules) + "\n"
        )
    print(f"{len(ICONS)} sprite icons, {len(rules)} table icons -> {OUT}")


if __name__ == "__main__":
    main()
